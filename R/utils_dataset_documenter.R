
#' utility for pkg devs to update or create documentation of datasets in the package
#'
#' @param varname character string text of name of object, like "blockgroupstats"
#' @param title same as the roxygen2 tag
#' @param description  same as the roxygen2 tag
#' @param details  same as the roxygen2 tag
#' @param seealso  same as the roxygen2 tag
#' @param saveinpackage if TRUE, puts quoted dataset name at end of file,
#'  and otherwise puts NULL at end of file
#' @param scriptname name of the data-raw script that creates this dataset,
#'  used in the header comment of the documentation file. Defaults to
#'  `datacreate_<varname>.R` (i.e., built from the varname); pass it
#'  explicitly when one script creates several datasets
#'  (e.g., datacreate_names_pct_as_fraction.R).
#' @details
#' see [article on updating datasets](`r paste0(EJAM::url_package("docs"), "/articles/dev-update-datasets.html")`)
#'
#' @return name of .R file where documentation was written
#'
#' @keywords internal
#'
dataset_documenter = function(varname,
                              title = "(varname) dataset",
                              description = "",
                              details = "",
                              seealso = "",
                              saveinpackage = TRUE,
                              scriptname = paste0("datacreate_", varname, ".R")) {

  # save very basic documentation for a dataset ####
  roxy_field <- function(tag, value) {
    if (identical(value, "")) {
      return("")
    }
    value <- gsub("\r\n?", "\n", value)
    lines <- strsplit(value, "\n", fixed = TRUE)[[1]]
    lines <- sub("^#'[ \t]?", "", lines)
    lines <- sub("[ \t]+$", "", lines)
    lines <- ifelse(nzchar(lines), paste0("#' ", lines), "#'")
    lines[1] <- sub("^#' ", paste0("#' @", tag, " "), lines[1], fixed = FALSE)
    paste0(paste(lines, collapse = "\n"), "\n")
  }

  if (length(varname) > 1 || !is.atomic(varname)) {
    stop("you may have provided the object instead of its name as the varname parameter -- try using quotes for that argument")
  }

  if (missing(title)) {
    title = paste0(varname,  " dataset")
  } else{
    title = title
  }

  title <- roxy_field("title", title)
  description <- roxy_field("description", description)
  details <- roxy_field("details", details)
  seealso <- roxy_field("seealso", seealso)

  # if dataset saved in pkg via use_data then the last line of the documentation file should be the name of the dataset in quotes.
  # if dataset NOT saved in pkg,  last line of doc file should be NULL without quotes,
  #   so it can create documentation as .Rd file without the object being available as something exported by the pkg.
  if (saveinpackage) {
    varnametext_or_null <- paste0("'", varname,"'")
  } else {
    varnametext_or_null <- "NULL"
    }

  filecontents <- paste0(
    "#\n\n# DO NOT EDIT THIS FILE - THIS DOCUMENTATION WAS CREATED BY A SCRIPT - see EJAM/data-raw/", scriptname, " or similar files\n\n",
    "#' @name ", varname, "
", "#' @docType data\n",
    title,
    description,
    details,
    seealso,
    varnametext_or_null
  )
  fname = paste0("./R/data_", varname, ".R")
  # save the .R file, but prefix documentation file names with "data_"
  writeLines(filecontents, con = fname, useBytes = TRUE)

  if (requireNamespace("rstudioapi", quietly = TRUE) && rstudioapi::isAvailable()) {
    rstudioapi::documentOpen(fname)
    rstudioapi::documentSave()
    rstudioapi::documentClose()
  }
  return(fname)
}
